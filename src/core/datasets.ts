const isNum = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v);

/**
 * Bytes as text, BASE-10 like the Android storage screen: 1 KB = 1000 B, 1 MB = 1 000 000 B. Whole bytes below 1 KB,
 * one decimal for KB, MB and GB ("999 B", "12.3 KB", "1.0 MB"). Not a number or negative gives "0 B".
 */
export function formatBytes(bytes: number | undefined | null): string {
  if (!isNum(bytes) || bytes <= 0) return '0 B';
  if (bytes < 1000) return `${Math.round(bytes)} B`;
  const units = ['KB', 'MB', 'GB', 'TB'];
  let v = bytes / 1000;
  let u = 0;
  while (Math.round(v * 10) / 10 >= 1000 && u < units.length - 1) {
    v /= 1000;
    u++;
  }
  return `${(Math.round(v * 10) / 10).toFixed(1)} ${units[u]}`;
}

/** A count with a thin space (U+2009) between thousands, as in Australian style guides ("7 368"). Non-finite gives "0". */
export function formatCount(n: number | undefined | null): string {
  if (!isNum(n)) return '0';
  const s = Math.round(n).toString();
  return s.replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

/** A share 0-1 as a percentage with one decimal below 10 % ("3.4 %", "12 %", "100 %"). */
export function formatPercent(fraction: number | undefined | null): string {
  if (!isNum(fraction)) return '0 %';
  const p = fraction * 100;
  if (p === 0) return '0 %';
  if (p !== 0 && Math.abs(p) < 0.1) return '<0.1 %';
  if (Math.abs(p) < 10) return `${(Math.round(p * 10) / 10).toFixed(1)} %`;
  return `${Math.round(p)} %`;
}

/** Epoch ms as an ISO date ('2026-09-29') in UTC; '' for a non-finite time. */
export function isoDate(ms: number | undefined | null): string {
  return isNum(ms) && ms > 0 ? new Date(ms).toISOString().slice(0, 10) : '';
}

/**
 * The calendar day ('2026-10-05') of an instant in New South Wales, where the app is used: a copy made at 06:12 on 5 October
 * (AEDT) is '2026-10-05', not the UTC date '2026-10-04', so it agrees with the times the screens show. '' for a non-finite time.
 */
export function localDay(ms: number | undefined | null, timeZone = 'Australia/Sydney'): string {
  if (!isNum(ms) || !(ms > 0)) return '';
  try {
    return new Intl.DateTimeFormat('en-CA', { timeZone, year: 'numeric', month: '2-digit', day: '2-digit' }).format(ms);
  } catch {
    return isoDate(ms);
  }
}

/** Epoch ms as 'yyyy-mm-dd hh:mm UTC'; '' for a non-finite time. */
export function isoDateTime(ms: number | undefined | null): string {
  return isNum(ms) && ms > 0 ? `${new Date(ms).toISOString().slice(0, 16).replace('T', ' ')} UTC` : '';
}

/** Duration in ms as '1.4 s' / '230 ms' / '2 min 5 s'. */
export function formatDuration(ms: number | undefined | null): string {
  if (!isNum(ms) || ms < 0) return '0 ms';
  if (ms < 1000) return `${Math.round(ms)} ms`;
  if (ms < 60_000) return `${(ms / 1000).toFixed(1)} s`;
  const m = Math.floor(ms / 60_000);
  return `${m} min ${Math.round((ms - m * 60_000) / 1000)} s`;
}

/** Age of a time in hours (never negative). */
export const ageHours = (thenMs: number, nowMs: number): number => Math.max(0, (nowMs - thenMs) / 3.6e6);

/** '3 h old', '25 min old', '2 days old'. */
export function formatAge(hours: number): string {
  if (!isNum(hours) || hours < 0) return 'just now';
  if (hours < 1) return `${Math.max(1, Math.round(hours * 60))} min old`;
  if (hours < 48) return `${Math.round(hours)} h old`;
  return `${Math.round(hours / 24)} days old`;
}

/** Staleness of a weather record per docs/research/08 §5.5: 6 h for a forecast, 24 h for a past-date series. */
export function weatherStaleness(rec: Pick<DatasetRecord, 'vintage' | 'origin' | 'status'> & { stats?: DatasetStat[] }, nowMs: number, kind: 'forecast' | 'past'): { ageHours: number; stale: boolean; thresholdHours: number; message: string } {
  const thresholdHours = WEATHER_STALE_HOURS[kind];
  const age = ageHours(rec.vintage.retrievedAt, nowMs);
  const stale = rec.origin !== 'preset' && rec.origin !== 'user' && rec.origin !== 'bundled' && age > thresholdHours;
  const what = rec.origin === 'live' ? 'downloaded' : 'stored';
  const message = stale
    ? `Using weather ${what} ${isoDateTime(rec.vintage.retrievedAt)}, ${formatAge(age)}: check it against your belt weather kit.`
    : `Weather ${what} ${formatAge(age)}.`;
  return { ageHours: age, stale, thresholdHours, message };
}

/** Canonical position of an id (unknown ids sort after the known ones). */
const orderOf = (id: string): number => {
  const i = (DATASET_IDS as readonly string[]).indexOf(id);
  return i < 0 ? DATASET_IDS.length : i;
};

/** Sorting keys of {@link sortDatasets}. */
export type DatasetSortKey = 'order' | 'role' | 'size' | 'network' | 'name' | 'status' | 'origin' | 'age';

const STATUS_RANK: Record<DatasetStatus, number> = { fallback: 0, unavailable: 1, partial: 2, skipped: 3, user: 4, used: 5 };

/** Canonical comparison: role order, then id order, then title. */
export function compareDatasets(a: DatasetRecord, b: DatasetRecord): number {
  const r = ROLE_ORDER.indexOf(a.role) - ROLE_ORDER.indexOf(b.role);
  if (r) return r;
  const o = orderOf(a.id) - orderOf(b.id);
  if (o) return o;
  return a.title.localeCompare(b.title, 'en');
}

/** A sorted COPY. 'size' and 'network' put the biggest first; 'status' puts the substitutes first; 'age' the oldest first. */
export function sortDatasets(records: readonly DatasetRecord[], by: DatasetSortKey = 'order'): DatasetRecord[] {
  const key: Record<DatasetSortKey, (r: DatasetRecord) => number | string> = {
    order: (r) => ROLE_ORDER.indexOf(r.role) * 1000 + orderOf(r.id),
    role: (r) => ROLE_ORDER.indexOf(r.role),
    size: (r) => -r.sizes.transferredBytes,
    network: (r) => -r.sizes.networkBytes,
    name: (r) => r.title.toLowerCase(),
    status: (r) => STATUS_RANK[r.status],
    origin: (r) => r.origin,
    age: (r) => r.vintage.retrievedAt,
  };
  const k = key[by];
  return [...records].sort((a, b) => {
    const x = k(a);
    const y = k(b);
    const c = typeof x === 'string' || typeof y === 'string' ? String(x).localeCompare(String(y), 'en') : x - y;
    return c || compareDatasets(a, b);
  });
}

export interface DatasetGroup {
  role: DatasetRole;
  title: string;
  records: DatasetRecord[];
  transferredBytes: number;
}

/** Records grouped by role in {@link ROLE_ORDER}; empty roles are left out. Records keep the canonical order inside a group. */
export function groupByRole(records: readonly DatasetRecord[]): DatasetGroup[] {
  const out: DatasetGroup[] = [];
  for (const role of ROLE_ORDER) {
    const rs = records.filter((r) => r.role === role).sort(compareDatasets);
    if (rs.length) out.push({ role, title: ROLE_TITLES[role], records: rs, transferredBytes: rs.reduce((s, r) => s + r.sizes.transferredBytes, 0) });
  }
  return out;
}

export const findDataset = (records: readonly DatasetRecord[] | undefined, id: DatasetId): DatasetRecord | undefined => records?.find((r) => r.id === id);

/** Data sets that are NOT what they say: a substitute, missing or partly filled. */
export const isSubstitute = (r: DatasetRecord): boolean => r.status === 'fallback' || r.status === 'unavailable' || r.status === 'partial';

/**
 * Credit lines for the map, de-duplicated, for the data sets that were really used (status used / partial / user, not a
 * fallback). Pass `ids` to restrict them to what is drawn (imagery, roads ...).
 */
export function creditLines(records: readonly DatasetRecord[] | undefined, ids?: readonly DatasetId[]): string[] {
  const out: string[] = [];
  for (const r of records ?? []) {
    if (ids && !ids.includes(r.id)) continue;
    if (r.status !== 'used' && r.status !== 'partial') continue;
    if (r.origin === 'synthetic' || r.origin === 'preset' || r.origin === 'user' || r.origin === 'derived') continue;
    if (r.role === 'bundle' || r.role === 'pack' || r.role === 'derived' || r.role === 'user') continue; // the app's own packaging and results
    const a = r.attribution.trim();
    if (a && !out.includes(a)) out.push(a);
  }
  return out;
}

/**
 * The imagery credit for the map, with its capture date: "Aerial photo © State of New South Wales (...), CC BY 4.0;
 * a mosaic of several capture dates (service © 2020)". Uses `vintage.capturedOn` when the photo has one date, else
 * `vintage.captureSummary`. '' when no imagery was used.
 */
export function imageryCredit(records: readonly DatasetRecord[] | undefined): string {
  const r = findDataset(records, 'imagery');
  if (!r || (r.status !== 'used' && r.status !== 'partial')) return '';
  const v = r.vintage;
  const when = v.capturedOn ? `; captured ${v.capturedOn}` : v.captureSummary ? `; ${v.captureSummary}` : '';
  return `Aerial photo ${r.attribution}${when}`;
}

/**
 * Typed-array memory reachable from a value: every distinct ArrayBuffer behind a typed array / DataView / ArrayBuffer is
 * counted ONCE (views sharing a buffer, and objects reached twice, are not double counted). Walks plain objects,
 * arrays, Maps and Sets, depth-first, up to `maxDepth` levels. `skip` holds objects not to enter (and whose buffers are
 * not counted), e.g. the scenario a simulation references. `byKey` adds up the bytes under each own key of the root.
 * Pure and bounded (visits each object once); used for the scenario's memory, the simulation's measured memory
 * (sim/simulation.ts `memoryReport`) and the memory-model tests. Pass the same `counted` set to several calls to split one
 * graph into parts (each buffer goes to the first part that reaches it).
 */
export function typedArrayFootprint(root: unknown, opts: { skip?: Iterable<unknown>; maxDepth?: number; counted?: Set<unknown> } = {}): { bytes: number; buffers: number; byKey: Record<string, number> } {
  const skip = new Set<unknown>(opts.skip ?? []);
  const seen = new Set<unknown>();
  // `counted` (shared between calls) lets several walks split one object graph without counting a buffer twice.
  const buffers = opts.counted ?? new Set<unknown>();
  const before = buffers.size;
  const skipBuffers = new Set<unknown>();
  const maxDepth = opts.maxDepth ?? 16;
  const byKey: Record<string, number> = {};
  let bytes = 0;
  const bufferOf = (v: object): { b: unknown; n: number } | null => {
    if (ArrayBuffer.isView(v)) return { b: v.buffer, n: v.buffer.byteLength };
    if (v instanceof ArrayBuffer) return { b: v, n: v.byteLength };
    if (typeof SharedArrayBuffer !== 'undefined' && v instanceof SharedArrayBuffer) return { b: v, n: v.byteLength };
    return null;
  };
  // Collect the skipped objects' buffers first: they are excluded even when also reachable from elsewhere.
  const collectSkip = (v: unknown, d: number, seenSkip: Set<unknown>): void => {
    if (!v || typeof v !== 'object' || seenSkip.has(v) || d > maxDepth) return;
    const b = bufferOf(v);
    if (b) {
      skipBuffers.add(b.b);
      return;
    }
    seenSkip.add(v);
    const kids = v instanceof Map ? [...v.values()] : v instanceof Set ? [...v] : Array.isArray(v) ? v : Object.values(v);
    for (const k of kids) collectSkip(k, d + 1, seenSkip);
  };
  const ss = new Set<unknown>();
  for (const s of skip) collectSkip(s, 0, ss);
  const stack: [unknown, string, number][] = [[root, '', 0]];
  while (stack.length) {
    const [v, key, d] = stack.pop()!;
    if (!v || typeof v !== 'object' || skip.has(v)) continue;
    const b = bufferOf(v);
    if (b) {
      if (buffers.has(b.b) || skipBuffers.has(b.b)) continue;
      buffers.add(b.b);
      bytes += b.n;
      if (key) byKey[key] = (byKey[key] ?? 0) + b.n;
      continue;
    }
    if (seen.has(v) || d > maxDepth) continue;
    seen.add(v);
    // Children are pushed in reverse so they are visited in their natural order (a shared buffer is counted under the
    // first key that reaches it).
    const kids: [unknown, string][] = [];
    if (v instanceof Map) for (const [k, x] of v) kids.push([x, key || String(k)]);
    else if (v instanceof Set) for (const x of v) kids.push([x, key]);
    else if (Array.isArray(v)) for (let i = 0; i < v.length; i++) kids.push([v[i], key]);
    else for (const k of Object.keys(v)) kids.push([(v as Record<string, unknown>)[k], key || k]);
    for (let i = kids.length - 1; i >= 0; i--) stack.push([kids[i]![0], kids[i]![1], d + 1]);
  }
  return { bytes, buffers: buffers.size - before, byKey };
}

