/**
 * Data-set provenance contract: what went into a scenario, how big it was, where it came from and how far to trust it.
 *
 * A {@link DatasetRecord} describes ONE data set of ONE scenario (terrain, imagery, vegetation, canopy, fire history,
 * weather, roads ...). The scenario builder (src/scenario/build.ts) measures every field at build time (bytes counted by
 * the request ledger src/data/ledger.ts, cells counted from the finished grids, times taken from the clock) and attaches
 * the result as `ScenarioData.datasets` and `ScenarioData.datasetSummary`. Only documented static facts are typed in
 * (provider and licence names, format names, the service copyright text). The Data sets screen, the map credits and the
 * exports read these records and never guess.
 *
 * This file is pure (types, constants and small helpers, no DOM, no I/O) so it can be used on the main thread, in the
 * worker and in tests. It is re-exported from core/types.ts.
 *
 * Conventions
 *  - Bytes are plain integers. {@link formatBytes} is BASE-10 (1 KB = 1000 B, like Android's storage screen), not KiB.
 *  - Times are epoch milliseconds (UTC); dates are ISO `yyyy-mm-dd` strings unless stated.
 *  - A field the builder could not measure is ABSENT, never a made-up zero: `sizes.decodedBytes` missing means "not
 *    measured". A real zero (e.g. `networkBytes: 0` for bundled data) is written as 0.
 *  - `stats[].value` is already formatted for display ("612 m"); `raw` and `unit` carry the number for sorting.
 */

