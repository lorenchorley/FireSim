/** WGS84 box and area of the square of side `extentM` around `centre`. */
export function extentOf(centre: LatLon, extentM: number): DatasetExtent {
  const p = new LocalProjection(centre);
  const h = extentM / 2;
  const sw = p.toLatLon(-h, -h);
  const ne = p.toLatLon(h, h);
  const r = (v: number): number => Math.round(v * 1e6) / 1e6;
  return { west: r(sw.lon), south: r(sw.lat), east: r(ne.lon), north: r(ne.lat), areaKm2: Math.round(((extentM * extentM) / 1e6) * 100) / 100 };
}

/** Epoch ms of an ISO date at 00:00 UTC, or 0. */
export const dateMs = (iso: string | undefined): number => {
  if (!iso) return 0;
  const t = Date.parse(/^\d{4}-\d{2}-\d{2}$/.test(iso) ? `${iso}T00:00:00Z` : iso);
  return Number.isFinite(t) ? t : 0;
};

export function endpoint(host: string, path: string, note?: string, requests?: number): DatasetEndpoint {
  return { host, path, ...(note ? { note } : {}), ...(requests !== undefined ? { requests } : {}) };
}

/** Endpoints a tag used, as DatasetEndpoints (from the ledger). */
export function endpointsOf(ledger: DatasetLedger | undefined, tags: readonly string[], note?: string): DatasetEndpoint[] {
  const out: DatasetEndpoint[] = [];
  for (const tag of tags) for (const e of ledger?.endpoints(tag) ?? []) out.push({ host: e.host, path: e.path, requests: e.requests, ...(note ? { note } : {}) });
  return out;
}

