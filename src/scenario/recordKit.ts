/** Vintage of data obtained live (this build), from a stored copy, or bundled. */
export function vintageFor(origin: DatasetOrigin, t: LedgerTotals, now: number, o: { capturedOn?: string; capturedNote?: string; bundleCapturedOn?: string; version?: string; versionNote?: string; currentTo?: string; cacheFreshUntil?: number; packCreatedAt?: number } = {}): DatasetVintage {
  const v: DatasetVintage = { retrievedAt: now, retrievedBasis: 'this-build' };
  if (origin === 'live') {
    v.retrievedAt = t.newestNetworkAt || now;
  } else if (origin === 'cache' || origin === 'area-pack') {
    v.retrievedAt = t.oldestCachedAt || o.packCreatedAt || 0;
    v.retrievedBasis = v.retrievedAt ? 'stored-copy' : 'unknown';
  } else if (origin === 'bundled') {
    v.retrievedAt = dateMs(o.bundleCapturedOn);
    v.retrievedBasis = v.retrievedAt ? 'bundle-capture' : 'unknown';
  } else if (origin === 'none') {
    v.retrievedAt = 0;
    v.retrievedBasis = 'unknown';
  } else {
    v.retrievedBasis = 'generated';
  }
  if (o.capturedOn) v.capturedOn = o.capturedOn;
  if (o.capturedNote) v.capturedNote = o.capturedNote;
  if (o.version) v.version = o.version;
  if (o.versionNote) v.versionNote = o.versionNote;
  if (o.currentTo) v.currentTo = o.currentTo;
  if (o.cacheFreshUntil) v.cacheFreshUntil = o.cacheFreshUntil;
  return v;
}

/** The record skeleton with empty lists; builders fill in the rest. */
export function skeleton(r: Pick<DatasetRecord, 'id' | 'role' | 'title' | 'what' | 'why' | 'provider' | 'licence' | 'attribution' | 'format' | 'kind' | 'status' | 'origin' | 'vintage' | 'coverage' | 'sizes' | 'evidence'> & Partial<DatasetRecord>): DatasetRecord {
  return { endpoints: [], sourceServices: [], stats: [], warnings: [], limitations: [], ...r };
}

/** A month/day-free ISO day of an epoch ms, '' when unknown. */
export const day = (ms: number): string => (ms > 0 ? new Date(ms).toISOString().slice(0, 10) : '');

/** "1 h", "3 days" style age from epoch ms. */
export function ageText(thenMs: number, nowMs: number): string {
  const h = Math.max(0, (nowMs - thenMs) / 3.6e6);
  if (h < 1) return `${Math.max(1, Math.round(h * 60))} min`;
  if (h < 48) return `${Math.round(h)} h`;
  return `${Math.round(h / 24)} days`;
}

/** Share (0-1) of the square (centre, side) that lies inside the square (c2, side2) (flat-earth, domain-sized squares). */
export function overlapShare(centre: LatLon, side: number, c2: LatLon, side2: number): number {
  const ky = 111195;
  const kx = ky * Math.cos((c2.lat * Math.PI) / 180);
  const dx = Math.abs((centre.lon - c2.lon) * kx);
  const dy = Math.abs((centre.lat - c2.lat) * ky);
  const ox = Math.max(0, Math.min(side / 2 + side2 / 2 - dx, side, side2));
  const oy = Math.max(0, Math.min(side / 2 + side2 / 2 - dy, side, side2));
  return Math.max(0, Math.min(1, (ox * oy) / (side * side)));
}
