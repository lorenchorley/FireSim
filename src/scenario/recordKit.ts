/** Add up the ledger totals of several tags (a data set may use more than one). */
export function sumTotals(ledger: DatasetLedger | undefined, tags: readonly string[]): LedgerTotals {
  const out = ledger?.totals('\u0000none') ?? emptyTotals();
  if (!ledger) return out;
  for (const tag of tags) {
    const t = ledger.totals(tag);
    out.requests += t.requests;
    out.failures += t.failures;
    out.bytes += t.bytes;
    out.bodyBytes += t.bodyBytes;
    out.networkBytes += t.networkBytes;
    out.cacheBytes += t.cacheBytes;
    out.packBytes += t.packBytes;
    out.bundledBytes += t.bundledBytes;
    out.retries += t.retries;
    out.sumMs += t.sumMs;
    for (const k of Object.keys(out.bySource) as (keyof LedgerTotals['bySource'])[]) out.bySource[k] += t.bySource[k];
    out.firstAt = out.firstAt && t.firstAt ? Math.min(out.firstAt, t.firstAt) : out.firstAt || t.firstAt;
    out.lastEndAt = Math.max(out.lastEndAt, t.lastEndAt);
    out.wallMs = out.lastEndAt - out.firstAt;
    out.oldestCachedAt = out.oldestCachedAt && t.oldestCachedAt ? Math.min(out.oldestCachedAt, t.oldestCachedAt) : out.oldestCachedAt || t.oldestCachedAt;
    out.newestCachedAt = Math.max(out.newestCachedAt, t.newestCachedAt);
    out.newestNetworkAt = Math.max(out.newestNetworkAt, t.newestNetworkAt);
    out.storedBytes += t.storedBytes;
  }
  return out;
}

function emptyTotals(): LedgerTotals {
  return {
    requests: 0, failures: 0, bytes: 0, bodyBytes: 0, networkBytes: 0, cacheBytes: 0, packBytes: 0, bundledBytes: 0,
    bySource: { network: 0, cache: 0, stale: 0, pack: 0, bundled: 0 }, retries: 0, sumMs: 0, wallMs: 0, firstAt: 0, lastEndAt: 0,
    oldestCachedAt: 0, newestCachedAt: 0, newestNetworkAt: 0, storedBytes: 0,
  };
}

/** DatasetSizes from ledger totals plus what the loader knows. Bundled bytes are in `transferredBytes` only. */
export function sizesOf(t: LedgerTotals, extra: Partial<DatasetSizes> = {}): DatasetSizes {
  return {
    transferredBytes: t.bytes,
    networkBytes: t.networkBytes,
    cachedBytes: t.cacheBytes + t.packBytes,
    requests: t.requests,
    ...(t.storedBytes > 0 ? { storedOnDeviceBytes: t.storedBytes } : {}),
    ...extra,
  };
}

/** Total byte length of typed arrays / buffers (undefined entries count 0). */
export function typedBytes(...arrays: (ArrayBufferView | ArrayBuffer | undefined | null)[]): number {
  let n = 0;
  for (const a of arrays) if (a) n += a.byteLength;
  return n;
}

/** Typed-array memory of an object's own array properties (one level). */
export function ownArrayBytes(o: object, skip: readonly string[] = []): number {
  let n = 0;
  for (const [k, v] of Object.entries(o)) if (!skip.includes(k) && ArrayBuffer.isView(v)) n += v.byteLength;
  return n;
}

