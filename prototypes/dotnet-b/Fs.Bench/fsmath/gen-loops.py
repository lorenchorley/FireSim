#!/usr/bin/env python3
"""Writes the per-function loops of T1.3: one loop per (function, implementation) with the call written out, so that timing a function does not include a
delegate call per element (a delegate or function pointer costs 1 to 2 ns, which is 10 % of a fast function).
    python3 -I Fs.Bench/fsmath/gen-loops.py bench > Fs.Bench/FsMathLoops.g.cs     fdlibm, cms, platform System.Math, FsMath's dispatcher; double[] arguments
    python3 -I Fs.Bench/fsmath/gen-loops.py wasm  > Fs.Wasm/FsMathLoops.g.cs      fdlibm and cms only (a solver project: no System.Math); Span arguments
"""
import sys

mode = sys.argv[1] if len(sys.argv) > 1 else 'bench'
fns = ["exp", "log", "pow", "sin", "cos", "tan", "atan", "atan2", "acos", "asin", "sinh", "cbrt", "log2", "log10", "hypot"]
arity = {"pow": 2, "atan2": 2, "hypot": 2}
cap = {"exp": "Exp", "log": "Log", "pow": "Pow", "sin": "Sin", "cos": "Cos", "tan": "Tan", "atan": "Atan", "atan2": "Atan2", "acos": "Acos", "asin": "Asin",
       "sinh": "Sinh", "cbrt": "Cbrt", "log2": "Log2", "log10": "Log10", "hypot": "Hypot"}
call = {
    "fdlibm": lambda f: f"FsMath.FdLibm.{cap[f]}" if f != "hypot" else "FsMath.Hypot",
    "cms": lambda f: f"FsMath.CoreMath.{cap[f]}" if f != "hypot" else "FsMath.Hypot",
    "platform": lambda f: "double.Hypot" if f == "hypot" else f"Math.{cap[f]}",
    "fsmath": lambda f: f"FsMath.{cap[f]}",
}
impls = ["fdlibm", "cms", "platform", "fsmath"] if mode == 'bench' else ["fdlibm", "cms"]
ns = "Fs.Bench" if mode == 'bench' else "Fs.Wasm"
xt, yt = ("double[]", "double[]") if mode == 'bench' else ("ReadOnlySpan<double>", "Span<double>")
print("// <auto-generated> by Fs.Bench/fsmath/gen-loops.py " + mode + ": do not edit by hand </auto-generated>")
print("using Fs.Kernel;")
print()
print(f"namespace {ns};")
print()
print("/// <summary>One loop per (function, implementation); each evaluates n calls (n pairs, interleaved, for two-argument functions) into y.</summary>")
print("public static class FsMathLoops")
print("{")
print(f"    public delegate void Loop({xt} x, {yt} y, int n);")
print()
for f in fns:
    for impl in impls:
        c = call[impl](f)
        if arity.get(f, 1) == 1:
            body = f"for (int i = 0; i < n; i++) y[i] = {c}(x[i]);"
        else:
            body = f"for (int i = 0; i < n; i++) y[i] = {c}(x[2 * i], x[2 * i + 1]);"
        print(f"    public static void {cap[f]}_{impl}({xt} x, {yt} y, int n) {{ {body} }}")
print()
print("    public static Loop Get(string impl, string fn) => (impl, fn) switch")
print("    {")
for f in fns:
    for impl in impls:
        print(f'        ("{impl}", "{f}") => {cap[f]}_{impl},')
print('        _ => throw new ArgumentException($"no loop for {impl}/{fn}"),')
print("    };")
print("}")
