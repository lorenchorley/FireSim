/**
 * T1.5 (a), (b): the Node runner of the TypeScript arms. One process = one arm configuration on one problem (a fresh process per fixture, as `air/bench.ts` and `fast/bench.ts` were run).
 *
 *   node arms-node.mjs --arm app|pool [--threads N] --mode verify|time --problem air:k3std|air:k6high|fast:k6f-900|fast:k6f-late --fixtures DIR --out FILE.json
 *        [--samples 1000] [--warm 1500] [--min-sample-ms 0] [--spin 200] [--only a,b]
 *
 * `--arm app`: one Node worker running the app's UNMODIFIED kernels, data resident in the worker, timing inside the worker (so no message passing is counted): the single-thread baseline
 * of Gates 1 and 1W (arm a). `--arm pool --threads N`: N workers (worker 0 drives and takes part) over one SharedArrayBuffer on the C# chunks (arm b); N = 1 is the range form without helpers.
 * FIXTURES holds air/fx-k3std, air/fx-k6high, fast/fx-k6f-900, fast/fx-k6f-late (regenerated by Fs.Bench/ts/air/regen.sh and fast/regen.sh).
 * Built with ../build.mjs together with worker-node.ts (the worker script is looked for next to this file).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Worker } from 'node:worker_threads';
import { runProblem, type RawFixture, type RunSpec, type WorkerHandle } from './orchestrate';

const here = dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const opt = (n: string, d?: string): string => {
  const i = argv.indexOf(`--${n}`);
  if (i >= 0) return argv[i + 1]!;
  if (d !== undefined) return d;
  throw new Error(`missing --${n}`);
};

function spawn(): WorkerHandle {
  const w = new Worker(join(here, 'worker-node.mjs'));
  const queue: Record<string, unknown>[] = [];
  let waiter: ((m: Record<string, unknown>) => void) | null = null;
  let failure: Error | null = null;
  let failWaiter: ((e: Error) => void) | null = null;
  w.on('message', (m: Record<string, unknown>) => {
    if (waiter) {
      const f = waiter;
      waiter = null;
      failWaiter = null;
      f(m);
    } else queue.push(m);
  });
  w.on('error', (e) => {
    failure = e as Error;
    if (failWaiter) failWaiter(e as Error);
  });
  return {
    post: (m) => w.postMessage(m),
    next: () =>
      new Promise((res, rej) => {
        if (failure) return rej(failure);
        const q = queue.shift();
        if (q) return res(q);
        waiter = res;
        failWaiter = rej;
      }),
    terminate: () => w.terminate(),
  };
}

const [kind, fixName] = opt('problem').split(':') as ['air' | 'fast', string];
const dir = join(opt('fixtures'), kind, `fx-${fixName}`);
const raw: RawFixture = { name: `fx-${fixName}`, header: readFileSync(join(dir, 'header.json'), 'utf8'), data: (() => { const b = readFileSync(join(dir, 'data.bin')); return b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength) as ArrayBuffer; })() };
const arm = opt('arm') as 'app' | 'pool';
const threads = arm === 'app' ? 1 : Number(opt('threads'));
const mode = opt('mode', 'time') as 'verify' | 'time';
const spec: RunSpec = {
  arm, threads, spinUs: Number(opt('spin', threads > os.cpus().length ? '0' : '200')), mode,
  samples: Number(opt('samples', fixName === 'k6high' ? '600' : '1000')), warmMs: Number(opt('warm', '1500')), minSampleMs: Number(opt('min-sample-ms', '0')),
  only: argv.includes('--only') ? opt('only').split(',') : undefined,
};

const loadStart = os.loadavg();
const workers: WorkerHandle[] = [];
for (let i = 0; i < threads; i++) workers.push(spawn());
let result: Record<string, unknown>;
try {
  result = await runProblem(workers, kind, raw, spec);
} finally {
  for (const w of workers) await w.terminate();
}
const loadEnd = os.loadavg();
const doc = {
  runtime: 'v8-node', problem: `${kind}:${fixName}`, arm, threads, spinUs: spec.spinUs, mode, samples: spec.samples, warmMs: spec.warmMs, minSampleMs: spec.minSampleMs,
  host: { cpu: os.cpus()[0]?.model, cores: os.cpus().length, node: process.version, v8: process.versions.v8, loadavgStart: loadStart, loadavgEnd: loadEnd, utc: new Date().toISOString() },
  result,
};
writeFileSync(opt('out'), JSON.stringify(doc));
const r = result as { verify?: { cases: number; checks: number; mismatches: number; failed: unknown[] }; stats?: { kernel: string; medianMs: number }[] };
if (r.verify) console.log(`${doc.problem} ${arm}${arm === 'pool' ? ' x' + threads : ''} verify: ${r.verify.cases} cases, ${r.verify.checks} hash checks, ${r.verify.mismatches} mismatches`);
if (r.verify && r.verify.mismatches > 0) console.log(JSON.stringify(r.verify.failed, null, 1));
if (r.stats) console.log(`${doc.problem} ${arm}${arm === 'pool' ? ' x' + threads : ''}: ` + r.stats.map((s) => `${s.kernel} ${s.medianMs.toFixed(4)}`).join(', '));
process.exit(r.verify && r.verify.mismatches > 0 ? 3 : 0);
