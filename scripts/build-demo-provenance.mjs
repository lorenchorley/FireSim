#!/usr/bin/env node
/**
 * Writes public/demo/provenance.json: what is bundled with the app and when it was captured. The Data sets screen,
 * the Setup size estimates and the storage report read it (src/data/bundleManifest.ts), so it must match the files.
 * `npm run provenance` regenerates it; src/data/bundleManifest.test.ts fails when it is out of date.
 *
 * Per site: bytes of every bundled file, the capture date of each, and counts (polygons, features, roads ...).
 * Capture date of a file, first that applies:
 *   1. `capturedOn` (or `fetched`) inside the file's sidecar JSON (dem5m.json, imagery.json, canopy.json, context.json)
 *      - the fetch scripts (fetch-demo-*.mjs) write it, and step 2 backfills the files fetched before they did;
 *   2. the date of the git commit that last changed the file (the data were committed the day they were fetched);
 *   3. absent (the app then says the capture date is unknown).
 *
 * Also stamps, once and idempotently, the sidecars that lack a capture date and corrects the elevation source text:
 * the NSW_5M_Elevation service describes itself as "5 metre post spacing elevation derived from stereo imagery"
 * (service metadata read 2026-09-29), not as LiDAR.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DEMO = `${ROOT}public/demo`;
const REPLAYS = `${ROOT}public/replays`;

const gitDate = (file) => {
  try {
    const rel = file.slice(ROOT.length);
    const dirty = execFileSync('git', ['status', '--porcelain', '--', rel], { cwd: ROOT, encoding: 'utf8' }).trim();
    if (dirty) return statSync(file).mtime.toISOString().slice(0, 10); // uncommitted: the day the file was written
    const d = execFileSync('git', ['log', '-1', '--format=%ad', '--date=short', '--', rel], { cwd: ROOT, encoding: 'utf8' }).trim();
    return d || undefined;
  } catch {
    return undefined;
  }
};

const readJson = (f) => {
  try {
    return JSON.parse(readFileSync(f, 'utf8'));
  } catch {
    return null;
  }
};
const size = (f) => (existsSync(f) ? statSync(f).size : 0);

const ELEVATION_SERVICE_TEXT = 'This Elevation service provides a full state cover of 5 metre post spacing elevation derived from stereo imagery.';
const ELEVATION_SOURCE = "NSW Spatial Services NSW_5M_Elevation ImageServer (5 m post-spacing elevation; the service describes it as 'derived from stereo imagery'), exportImage F32 GeoTIFF in EPSG:3857, bilinear-resampled to 10 m local grid";

/** Add capture date and service text to a sidecar without touching anything else. Returns true when it changed. */
function stamp(file, patch) {
  const j = readJson(file);
  if (!j) return false;
  let changed = false;
  for (const [k, v] of Object.entries(patch)) {
    if (v !== undefined && JSON.stringify(j[k]) !== JSON.stringify(v)) {
      j[k] = v;
      changed = true;
    }
  }
  if (changed) writeFileSync(file, JSON.stringify(j, null, 1));
  return changed;
}

const sites = readdirSync(DEMO, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
const out = {
  version: 1,
  note: 'Generated by scripts/build-demo-provenance.mjs (npm run provenance). Sizes are file byte lengths; capturedOn is the day the file was fetched from the provider.',
  sites: {},
  replays: { totalBytes: 0, files: {} },
};

for (const id of sites) {
  const dir = `${DEMO}/${id}`;
  const cap = (name) => gitDate(`${dir}/${name}`);
  // Backfill capture dates into the small sidecars, and the truthful elevation description.
  const demDate = readJson(`${dir}/dem5m.json`)?.capturedOn ?? cap('dem5m.png') ?? cap('dem5m.json');
  stamp(`${dir}/dem5m.json`, { source: ELEVATION_SOURCE, capturedOn: demDate, serviceCopyright: 'DFSI 2019', serviceDescription: ELEVATION_SERVICE_TEXT });
  stamp(`${dir}/imagery.json`, {
    capturedOn: readJson(`${dir}/imagery.json`)?.capturedOn ?? cap('imagery.jpg'),
    serviceCopyright: '© Department of Customer Service 2020',
  });
  stamp(`${dir}/canopy.json`, { capturedOn: readJson(`${dir}/canopy.json`)?.capturedOn ?? cap('canopy.png') });
  stamp(`${dir}/manifest.json`, { capturedOn: readJson(`${dir}/manifest.json`)?.capturedOn ?? cap('manifest.json') });

  const files = {};
  const add = (name, capturedOn, extra = {}) => {
    const f = `${dir}/${name}`;
    if (existsSync(f)) files[name] = { bytes: size(f), ...(capturedOn ? { capturedOn } : {}), ...extra };
  };
  add('dem5m.png', readJson(`${dir}/dem5m.json`)?.capturedOn);
  add('dem5m.json', readJson(`${dir}/dem5m.json`)?.capturedOn);
  add('imagery.jpg', readJson(`${dir}/imagery.json`)?.capturedOn);
  add('imagery.json', readJson(`${dir}/imagery.json`)?.capturedOn);
  add('canopy.png', readJson(`${dir}/canopy.json`)?.capturedOn);
  add('canopy.json', readJson(`${dir}/canopy.json`)?.capturedOn);
  const veg = readJson(`${dir}/vegetation.geojson`);
  add('vegetation.geojson', veg?.capturedOn ?? cap('vegetation.geojson'), { features: veg?.features?.length ?? 0 });
  const fh = readJson(`${dir}/fire-history.geojson`);
  add('fire-history.geojson', fh?.capturedOn ?? cap('fire-history.geojson'), {
    features: fh?.features?.length ?? 0,
    ...(fh ? { verDate: Math.max(0, ...fh.features.map((f) => Number(f.properties?.VerDate) || 0)) || undefined } : {}),
  });
  const ctx = readJson(`${dir}/context.json`);
  // layerBytes: the size of each layer's JSON in the shared file, so the Setup plan splits its size the way the built records do
  // (src/scenario/datasetRecordsPlaces.ts layerShares).
  add(
    'context.json',
    ctx?.fetched ?? cap('context.json'),
    ctx
      ? {
          roads: ctx.roads.length,
          fireTrails: ctx.fireTrails.length,
          zones: ctx.zones.length,
          homes: ctx.homes.length / 2,
          places: ctx.places.length,
          layerBytes: {
            roads: JSON.stringify(ctx.roads).length,
            fireTrails: JSON.stringify(ctx.fireTrails).length,
            homes: JSON.stringify(ctx.homes).length,
            zones: JSON.stringify(ctx.zones).length,
            places: JSON.stringify(ctx.places).length,
          },
        }
      : {},
  );
  add('manifest.json', readJson(`${dir}/manifest.json`)?.capturedOn);
  // Terrarium tiles: one line for the folder.
  let tiles = 0;
  let tileBytes = 0;
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = `${d}/${e.name}`;
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith('.png')) {
        tiles++;
        tileBytes += statSync(p).size;
      }
    }
  };
  if (existsSync(`${dir}/terrarium`)) walk(`${dir}/terrarium`);
  if (tiles) files['terrarium'] = { bytes: tileBytes, count: tiles, ...(readJson(`${dir}/manifest.json`)?.capturedOn ? { capturedOn: readJson(`${dir}/manifest.json`).capturedOn } : {}) };
  out.sites[id] = { totalBytes: Object.values(files).reduce((s, f) => s + f.bytes, 0), files };
}

if (existsSync(REPLAYS)) {
  for (const name of readdirSync(REPLAYS).sort()) {
    if (!name.endsWith('.json')) continue;
    const f = `${REPLAYS}/${name}`;
    const bytes = size(f);
    out.replays.files[name] = { bytes, ...(gitDate(f) ? { capturedOn: gitDate(f) } : {}) };
    out.replays.totalBytes += bytes;
  }
}
out.totalBytes = Object.values(out.sites).reduce((s, x) => s + x.totalBytes, 0) + out.replays.totalBytes;
writeFileSync(`${DEMO}/provenance.json`, JSON.stringify(out, null, 1) + '\n');
console.log(`wrote public/demo/provenance.json: ${sites.length} sites, ${out.totalBytes} bytes`);
